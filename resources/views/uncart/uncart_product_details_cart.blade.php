    closeCartBtn.addEventListener('click', closeCart);
    cartBackdrop.addEventListener('click', closeCart);

    // Quantity Stepper
    let currentQty = 1;
    function changeQty(delta) {
      currentQty = Math.max(1, currentQty + delta);
      document.getElementById('productQty').textContent = currentQty;
    }

    // Color Swatch Selection
    function selectColor(btn, name) {
      document.querySelectorAll('.color-swatch').forEach(el => {
        el.classList.remove('ring-2', 'ring-primary', 'ring-offset-2', 'ring-offset-background');
      });
      btn.classList.add('ring-2', 'ring-primary', 'ring-offset-2', 'ring-offset-background');
      document.getElementById('selectedColorLabel').textContent = name;
    }

    // Edition / Sizing Selection
    function selectEdition(btn) {
      document.querySelectorAll('.edition-btn').forEach(el => {
        el.classList.remove('border-secondary', 'bg-surface-container-high/60');
        el.classList.add('border-outline-variant/30');
      });
      btn.classList.remove('border-outline-variant/30');
      btn.classList.add('border-secondary', 'bg-surface-container-high/60');
    }

    // Thumbnail Switcher
    function switchImage(button) {
      document.querySelectorAll('.thumb-btn').forEach(b => {
        b.classList.remove('border-secondary', 'border-2');
