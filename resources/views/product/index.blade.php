function changeQty(delta) {
    const qtyEl = document.getElementById('productQty');
    if (!qtyEl) return;
    let current = parseInt(qtyEl.textContent) || 1;
    current = Math.max(1, current + delta);
    qtyEl.textContent = current;
}

function triggerAddToCart(goCheckout = false) {
    const qty = parseInt(document.getElementById('productQty')?.textContent || 1);
    const title = {!! json_encode($product->name) !!};
    const price = {{ $product->price }};
    const productId = {{ $product->id }};
    const imagePath = {!! json_encode($product->display_image) !!};

    addToBag(title, price, productId, qty, imagePath);

    if (goCheckout) {
        setTimeout(() => {
            window.location.href = '{{ route("checkout.index") }}';
        }, 500);
    }
}
